/// Lookup the Script type for `cp`.
pub fn script(cp: u21) ?Script {
    const byte = scripts.s3[scripts.s2[scripts.s1[cp >> 8] + (cp & 0xff)]];
    if (byte == 0) return null;
    return @enumFromInt(byte);
}

