    try testing.expectEqual(Script.Latin, script('A').?);
    // try testing.expectEqual(Script.Deseret, script('𐐌').?);
}

test "Unicode 17 and 18 scripts" {
    try testing.expectEqual(.Beria_Erfe, script(0x16ea0).?);
    try testing.expectEqual(.Sidetic, script(0x10940).?);
    try testing.expectEqual(.Tai_Yo, script(0x1e6c0).?);
    try testing.expectEqual(.Tolong_Siki, script(0x11db0).?);
    try testing.expectEqual(.Jurchen, script(0x18e00).?);
    try testing.expectEqual(.Jurchen, script(0x191d2).?);
    try testing.expectEqual(.Proto_Cuneiform, script(0x125a8).?);
    try testing.expectEqual(.Proto_Cuneiform, script(0x1264b).?);
    try testing.expectEqual(.Seal, script(0x3d000).?);
    try testing.expectEqual(.Seal, script(0x3fc3f).?);
    try testing.expectEqual(null, script(0x3fc40));
}

